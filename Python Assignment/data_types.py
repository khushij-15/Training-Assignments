# data types in python

'''
Concepts Covered:
1. Data Types in Python
2. Type Conversion
3. Checking Data Types
Python has several built-in data types, including:
1. Integers
2. Strings (F-strings)
3. Booleans
4. Lists
5. Tuples
6. Sets
7. Dictionaries
'''

# Integer data type
print("Integer Data Type: ")
age = 25
print("Age:", age)
print("Type of age:", type(age))

# String data type
print("\nString Data Type: ")
name = "Alice"
print("Name:", name)
print("Type of name:", type(name))

# Boolean data type
print("\nBoolean Data Type: ")
is_student = True
print("Is Student:", is_student)
print("Type of is_student:", type(is_student))

# List data type
print("\nList Data Type: ")
fruits = ["apple", "banana", "orange"]
print("Fruits:", fruits)
print("Type of fruits:", type(fruits))

# Tuple data type
print("\nTuple Data Type: ")
coordinates = (10, 20)
print("Coordinates:", coordinates)
print("Type of coordinates:", type(coordinates))

# Set data type
print("\nSet Data Type: ")
unique_numbers = {1, 2, 3, 4, 5}
print("Unique Numbers:", unique_numbers)
print("Type of unique_numbers:", type(unique_numbers))

# Dictionary data type
print("\nDictionary Data Type: ")
person = {"name": "Bob", "age": 30, "city": "New York"}
print("Person:", person)
print("Type of person:", type(person))
